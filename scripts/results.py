"""Fill README.md's Results block (between the RESULTS markers) from the eval reports and the cost
ledger, so the tables never drift from the measurements. $0; run after the evals.

    uv run python scripts/results.py
"""

from __future__ import annotations

import json
import re

from rich.console import Console

from litreview.config import PROJECT_ROOT, get_settings

REPORTS = PROJECT_ROOT / "evals" / "reports"
README = PROJECT_ROOT / "README.md"
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
PENDING = "_not measured yet: {}_"
console = Console()


def load(name: str):
    path = REPORTS / name
    return json.loads(path.read_text()) if path.exists() else None


def retrieval_table() -> str:
    rows = load("retrieval.json")
    if not rows:
        return PENDING.format("`uv run python -m evals.retrieval --no-router --apply`")
    lines = [
        "| config | hit@5 | MRR | papers@5 |",
        "|---|---|---|---|",
    ]
    for r in sorted(rows, key=lambda r: (-r["hit_rate"], -r["mrr"])):
        retriever = "router" if r["router"] else "vector"
        name = f"{r['splitter']}, rerank {'on' if r['rerank'] else 'off'}, {retriever}"
        if r.get("diverse"):
            name += ", <=2 chunks/paper"
        papers = f"{r['papers_at_5']:.1f}" if "papers_at_5" in r else "n/a"
        lines.append(f"| {name} | {r['hit_rate']:.2f} | {r['mrr']:.2f} | {papers} |")
    return "\n".join(lines) + "\n\nTarget (spec): hit@5 >= 0.80."


def citations_table() -> str:
    data = load("citations.json")
    if not data:
        return PENDING.format("`uv run python -m evals.citations`")
    m = data["metrics"]
    met = m["supported_lenient_pct"] >= 95 and m["unknown_node_pct"] == 0
    return "\n".join(
        [
            "| metric | value | target |",
            "|---|---|---|",
            f"| cited sentences checked | {m['cited_sentences']} in {m['reviews']} reviews | |",
            f"| supported (strict) | {m['supported_strict_pct']}% | |",
            f"| supported + partially | {m['supported_lenient_pct']}% | >= 95% |",
            f"| unknown nodes | {m['unknown_node_pct']}% | 0% |",
            f"| judge vs FaithfulnessEvaluator agreement | {m['faithfulness_agreement_pct']}% | |",
            "",
            f"Acceptance: **{'met' if met else 'not met'}**.",
        ]
    )


def quality_table() -> str:
    data = load("quality.json")
    if not data:
        return PENDING.format("`uv run python -m evals.quality judge`")
    criteria = ("coverage", "structure", "no_fabrication", "hedging")
    lines = ["| review | " + " | ".join(criteria) + " |", "|---" * (len(criteria) + 1) + "|"]
    for name, s in data["scores"].items():
        lines.append(f"| {name[:50]} | " + " | ".join(str(s[c]["score"]) for c in criteria) + " |")
    human = data.get("human_agreement_mad")
    note = (
        f" Mean |you - judge|: {human}." if human else " Blind human scores: `evals.quality sheet` / `agree`."
    )
    return "\n".join(lines) + f"\n\nJudge: {data['judge_model']}, mean {data['mean_pct']}%.{note}"


def comparison_table() -> str:
    runs = load("compare.json")
    if not runs:
        return PENDING.format("`uv run python scripts/compare_workflows.py`")
    lines = [
        "| workflow | runs ok | cost / review | LLM calls | wall time | citation score | papers cited |",
        "|---|---|---|---|---|---|---|",
    ]
    for wf in ("explicit", "agentic"):
        all_runs = [r for r in runs if r["workflow"] == wf]
        ok = [r for r in all_runs if r["ok"]]

        def avg(key: str, rs=ok) -> float | None:
            vals = [r[key] for r in rs if r.get(key) is not None]
            return sum(vals) / len(vals) if vals else None

        def fmt(x, spec: str) -> str:
            return "n/a" if x is None else format(x, spec)

        cells = [
            wf,
            f"{len(ok)}/{len(all_runs)}",
            f"${fmt(avg('cost_usd'), '.4f')}",
            fmt(avg("llm_calls"), ".0f"),
            f"{fmt(avg('seconds'), '.0f')}s",
            fmt(avg("citation_score"), ".0%"),
            fmt(avg("papers"), ".1f"),
        ]
        lines.append("| " + " | ".join(cells) + " |")
    return (
        "\n".join(lines)
        + "\n\nDetails and your notes: [docs/explicit-vs-agentic.md](docs/explicit-vs-agentic.md)."
    )


def spend() -> str:
    ledger = get_settings().p2_runs_dir / "costs.jsonl"
    rows = [json.loads(line) for line in ledger.read_text().splitlines()] if ledger.exists() else []
    total = sum(r["cost_usd"] for r in rows)
    return f"{len(rows)} LLM calls, **${total:.2f}** of the ${get_settings().p2_spend_cap_usd:.0f} cap."


def block() -> str:
    return "\n\n".join(
        [
            START,
            "_Generated by `scripts/results.py` from `evals/reports/` and `runs/costs.jsonl`._",
            "### Retrieval (40 labeled questions, paper level)",
            retrieval_table(),
            "### Citation faithfulness",
            citations_table(),
            "### Review quality",
            quality_table(),
            "### Explicit workflow vs agents (cost per review, wall time)",
            comparison_table(),
            "### Total spend",
            spend(),
            END,
        ]
    )


def main() -> None:
    text = README.read_text()
    if START not in text:
        raise SystemExit(f"README.md has no {START} marker")
    README.write_text(re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block(), text, flags=re.S))
    console.print(f"updated the Results block in {README}")


if __name__ == "__main__":
    main()
